"""SL-24 Part B: the figure and table fixes of the pre-E1 reports (A17 §5).

- E2 agent payments under agent-aware lists are split by the A1 §E5 screen, with the
  δ = 0 level (A17 §5.2);
- every E2 and E3 output the guardrail floor affects reports the paper-feasible subset
  or states which markets it shows (A17 §5.1);
- the E3 overflow panel shows y* = 1 for Δ > λ at every ω;
- no legend sits inside an axes: ``figures.save`` gathers legends into a band above them;
- every figure and table keeps the A17 label;
- the defect found in the audit (the E2 gating-gain figure bootstrapped its interval on a
  different market set from its mean) stays fixed.

The reports themselves are regenerated by ``e2_report``, ``e3_report`` and ``e4_report``;
these tests read their committed outputs.
"""
from __future__ import annotations

import csv
import json
import re
import unittest
from pathlib import Path

import matplotlib.pyplot as plt
from features.storelab.analysis import e2_report, e3_report, e4_report, figures
from features.storelab.analysis.figures import FIGURES, LABEL

ANALYSIS = Path(e2_report.__file__).resolve().parent


def read_csv(path: Path) -> list[dict]:
    lines = path.read_text(encoding="utf-8").splitlines()
    assert lines[0] == "# " + LABEL, path
    return list(csv.DictReader(lines[1:]))


def summary(module) -> dict:
    return json.loads(module.SUMMARY.read_text(encoding="utf-8"))


class LegendTest(unittest.TestCase):
    def test_save_moves_every_legend_out_of_the_axes(self):
        fig, axes = figures.figure(1, 2, 6.0, 3.0)
        for ax in axes[0]:
            ax.plot([0, 1], [0, 1], label="a")
            ax.plot([0, 1], [1, 0], label="b")
            ax.legend()
        tmp = "sl24_test"
        try:
            figures.save(fig, tmp, "legend", ["x"], [(1,)], "title", legend=2)
            self.assertEqual([ax.get_legend() for ax in fig.axes], [None, None])
            self.assertEqual(len(fig.legends), 1)
            self.assertEqual([t.get_text() for t in fig.legends[0].get_texts()], ["a", "b"])  # one entry per label
            top = min(ax.get_position().y1 for ax in fig.axes)
            self.assertGreaterEqual(fig.legends[0].get_window_extent().transformed(
                fig.transFigure.inverted()).y0, top)  # the band lies above every axes
        finally:
            plt.close(fig)
            for path in (FIGURES / tmp).glob("*"):
                path.unlink()
            (FIGURES / tmp).rmdir()

    def test_no_report_draws_a_legend_inside_an_axes(self):
        for name in ("e2_report.py", "e3_report.py", "e4_report.py"):
            with self.subTest(report=name):
                self.assertNotRegex((ANALYSIS / name).read_text(encoding="utf-8"), r"\bax\.legend\(")


class LabelTest(unittest.TestCase):
    def test_every_figure_and_table_keeps_the_a17_label(self):
        for module, ticket in ((e2_report, "sl19s"), (e3_report, "sl20s"), (e4_report, "sl21s")):
            for name in module.FIGURE_NAMES:
                with self.subTest(figure=name):
                    for suffix in (".pdf", ".png"):
                        self.assertTrue((FIGURES / ticket / (name + suffix)).exists())
                    self.assertTrue((FIGURES / ticket / (name + ".csv")).read_text(encoding="utf-8").startswith(
                        "# " + LABEL))
            for path in module.TABLES.glob("*.csv"):
                with self.subTest(table=str(path)):
                    self.assertTrue(path.read_text(encoding="utf-8").startswith("# " + LABEL))
            self.assertIn(LABEL, module.REPORT.read_text(encoding="utf-8"))


class E2Test(unittest.TestCase):
    def test_agent_payments_are_split_by_the_screen_with_the_delta_0_level(self):
        rows = read_csv(FIGURES / "sl19s" / "7_agent_payments_by_screen.csv")
        groups = {(r["subset"], r["group"]) for r in rows}
        self.assertEqual(groups, {(s, g) for s in e2_report.SUBSETS for g in ("screen_pass", "screen_fail", "delta_0")})
        self.assertEqual({r["mechanism"] for r in rows}, set(e2_report.MECHANISMS))
        counts = {(r["group"], r["alpha"]): int(r["markets"]) for r in rows if r["subset"] == "all"
                  and r["mechanism"] == "M3"}
        for alpha in ("0.25", "0.5", "0.75", "1.0"):  # pass + fail = every aware-feasible baseline market
            self.assertEqual(counts[("screen_pass", alpha)] + counts[("screen_fail", alpha)], 200)
            self.assertEqual(counts[("delta_0", alpha)], 200)  # with δ = 0 every market passes the screen
        stats_ = summary(e2_report)["statistics"]["H2a"]["part1"]
        for alpha in (0.25, 0.5, 0.75, 1.0):  # the screen-passing counts are those of H2a part 1
            self.assertEqual(counts[("screen_pass", repr(alpha))],
                             stats_["core/alpha=%g/agent_aware/none" % alpha]["n"])
        # figure 1 no longer pools agent-aware agent payments across the screen
        self.assertNotIn("agent_aware,agent,", (FIGURES / "sl19s" / "1_payments_by_traffic_type.csv").read_text())

    def test_floor_affected_outputs_report_the_paper_feasible_subset(self):
        s = summary(e2_report)
        self.assertEqual(set(s["floor_share"]), {"human_optimised", "agent_aware", "gated"})
        self.assertEqual(set(s["statistics_paper_feasible"]), {"H2a", "H2b", "H2c"})
        means = read_csv(e2_report.TABLES / "means.csv")
        self.assertEqual({r["subset"] for r in means}, set(e2_report.SUBSETS))
        self.assertEqual({r["subset"] for r in read_csv(e2_report.TABLES / "paired_differences.csv")},
                         set(e2_report.SUBSETS))
        all_n = {(r["config_id"], r["mechanism"]): int(r["markets"]) for r in means if r["subset"] == "all"}
        for r in means:
            if r["subset"] == "paper_feasible":
                self.assertLessEqual(int(r["markets"]), all_n[(r["config_id"], r["mechanism"])])
        for name in ("4_setblind_gap", "6_agent_payments_vs_excess", "7_agent_payments_by_screen"):
            self.assertEqual({r["subset"] for r in read_csv(FIGURES / "sl19s" / (name + ".csv"))},
                             set(e2_report.SUBSETS), name)
        report = e2_report.REPORT.read_text(encoding="utf-8")
        self.assertIn("Paper-feasible subset (A17 §5.1)", report)
        for name, caption in e2_report.FIGURE_CAPTIONS.items():  # every figure states which markets it shows
            self.assertIn("%s.pdf`: %s" % (name, caption), report)
            self.assertRegex(caption, r"all markets|paper's guardrail")

    def test_the_gating_gain_interval_is_on_the_markets_of_its_mean(self):
        rows = read_csv(FIGURES / "sl19s" / "5_gating_gain.csv")
        markets = summary(e2_report)["statistics"]["H2b"]["markets"]
        for r in rows:
            with self.subTest(alpha=r["alpha"]):
                self.assertEqual(int(r["markets"]), markets)
                self.assertLessEqual(float(r["ci_low"]), float(r["mean_gain_per_request"]))
                self.assertGreaterEqual(float(r["ci_high"]), float(r["mean_gain_per_request"]))


class E3Test(unittest.TestCase):
    def test_the_overflow_panel_shows_y_star_1_above_lambda_at_every_omega(self):
        rows = [r for r in read_csv(FIGURES / "sl20s" / "2_y_star_vs_delta.csv") if r["case"] == "overflow_limit"]
        omegas = {r["omega"] for r in rows}
        self.assertEqual(omegas, {"0.3", "0.5", "0.8", "1.0"})
        for omega in omegas:
            above = [r for r in rows if r["omega"] == omega and float(r["delta"]) > 1.0]
            with self.subTest(omega=omega):
                self.assertTrue(any(r["series"] == "closed form" for r in above))
                self.assertTrue(any(r["series"] == "numeric" for r in above))
                self.assertTrue(all(abs(float(r["y"]) - 1.0) <= 1e-4 for r in above))
        source = (ANALYSIS / "e3_report.py").read_text(encoding="utf-8")
        self.assertIn("for every ω", source)  # the panel's annotation

    def test_h3c_reports_the_paper_feasible_subset(self):
        h = summary(e3_report)["statistics"]["H3c"]
        self.assertEqual(set(h["paper_feasible"]), {"M3", "M4"})
        for m in ("M3", "M4"):
            self.assertLess(h["paper_feasible"][m]["markets"], h[m]["markets"])
            self.assertEqual(h["paper_feasible"][m]["floor_binds_markets"], 0)
        rows = read_csv(FIGURES / "sl20s" / "5_h3c_buyback.csv")
        self.assertEqual({r["subset"] for r in rows}, {"all markets", "paper-feasible subset"})
        report = e3_report.REPORT.read_text(encoding="utf-8")
        self.assertIn("paper-feasible subset", report)
        self.assertIn("the floor does not apply", report)  # the Part B figures state it


class E4Test(unittest.TestCase):
    def test_h4b_is_read_under_amendment_1(self):
        cells = summary(e4_report)["statistics"]["H4b"]["cells"]
        level = 1 - 0.05 / len(cells)
        for key, v in cells.items():
            a = v["amendment_1"]
            with self.subTest(cell=key):
                self.assertAlmostEqual(a["level"], level)
                self.assertNotEqual(a["outcome"], "implementation_error")
                self.assertLessEqual(a["ci"][0], v["ci95"][0])  # the Bonferroni interval is the wider one
                self.assertGreaterEqual(a["ci"][1], v["ci95"][1])
                self.assertEqual(a["outcome"], "passes" if a["half_width"] <= 0.05 else "precision_too_low")
        mc = summary(e4_report)["statistics"]["H4b"]["implementation_check_monte_carlo"]
        self.assertTrue(mc["passes"])
        self.assertGreater(mc["adjusted_bound_at_worst"], mc["raw_tolerance"])
        self.assertTrue(re.search(r"A12 §6\.3", e4_report.REPORT.read_text(encoding="utf-8")))


if __name__ == "__main__":
    unittest.main()
